"""Corrected RCW (Rodgers, Campbell & Whiteoak 1960) positions -- Kevin Jardine's
"Integrated HII Regions" catalog (galaxymap.org, Creative Commons licensed), covering
only the RCW-tagged rows. Same source, same rationale, same "positions only" scope as
sh2_corrected_positions.py -- see that module's own docstring for the full precedent.

Confirmed real, user-facing problem: a live test with RCW107 showed its marker sitting
visibly off the actual object. VII/216 (this app's only current source for RCW, via
VizierProvider) stores each object's position at only minute precision in RA and
whole-arcminute precision in Dec (its own RAB1950/DEB1950 columns) -- for RCW107 that
rounding alone is enough for VII/216's derived J2000 position (16 33 30.8, -48 09 17)
to land about 2.5 arcmin from the object's real position. SIMBAD resolves "RCW 107" to
HD 148937, the star powering the NGC 6164/6165 nebula it catalogs, at
16 33 52.39, -48 06 40.5 -- within ~6" of this module's Jardine-sourced position
(16 33 48.59, -48 06 46.3), confirming this source is a real, substantial improvement
over VII/216's own coordinates for RCW specifically, not just for Sh2.

Downloaded and converted once (sexagesimal RA/Dec -> decimal degrees) from
http://galaxymap.org/integrated/integrated_hii_release.xls (its "rcw" column),
retrieved 2026-09-02. Only rows with a plain numeric RCW number are included here (a
handful of rows carry a letter-suffixed value like "146a" that doesn't correspond to
any VII/216 designation -- including those would just add unmergeable extra "rcw"
entries rather than correcting an existing one, so they're deliberately skipped, same
reasoning as CORRECTED_SH2_POSITIONS' own int-only keys). Positions only, per the same
precedent as Sh2 -- angular_size/etc. still get backfilled from VII/216 via
CompositeProvider's existing same-designation merge (see RcwCorrectedPositionProvider
in catalogs.py).

Explicitly experimental and meant to be trivially reversible if manual verification in
Siril doesn't bear this out: this module plus RcwCorrectedPositionProvider in
catalogs.py plus its one registration line in gui/main_window.py's _catalog_provider
are the entire change -- reverting the single commit that introduced them fully undoes
it.
"""

